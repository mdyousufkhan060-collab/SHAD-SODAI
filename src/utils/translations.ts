export const getTranslatedName = (name: string, lang: 'bn' | 'en') => {
  const match = name.match(/^(.*?)\s*\((.*?)\)$/);
  if (match) {
    return lang === 'bn' ? match[2] : match[1];
  }
  return name;
};

